# 2. Funzione per caricare i CSV e parsare il timestamp
def load_and_prep(csv_str, col_name):
    df = pd.read_csv(StringIO(csv_str), names=['Timestamp', col_name])
    df['Time'] = pd.to_datetime(df['Timestamp'], unit='s')
    df.set_index('Time', inplace=True)
    df.drop(columns=['Timestamp'], inplace=True)
    return df

df_cpu = load_and_prep(csv_cpu, 'CPU_Perc')
df_ram = load_and_prep(csv_ram, 'RAM_Bytes')
df_net = load_and_prep(csv_net_rx, 'Net_Bytes_Sec')
df_io = load_and_prep(csv_io, 'IO_Bytes_Sec')

# Unione in un singolo DataFrame
df = df_cpu.join([df_ram, df_net, df_io], how='inner')

# 3. Conversioni dei formati
df['RAM_GB'] = df['RAM_Bytes'] / (1024 ** 3)        # Da Bytes a GB
df['Net_Mbps'] = (df['Net_Bytes_Sec'] * 8) / 1e6    # Da Bytes/sec a Megabits/sec
df['IO_MBps'] = df['IO_Bytes_Sec'] / (1024 ** 2)    # Da Bytes/sec a MB/sec

# 4. Configurazione dei Subplot (2 righe, 1 colonna)
fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(14, 10), sharex=True)
fig.suptitle("Analisi Prestazionale: Nodo Stateless ZeroNethermind", fontsize=16)

# --- Subplot 1: CPU & RAM ---
color_cpu = 'tab:red'
ax1.plot(df.index, df['CPU_Perc'], color=color_cpu, label='CPU Usage (%)', linewidth=2)
ax1.set_ylabel('CPU Usage (%)', color=color_cpu, fontsize=12)
ax1.tick_params(axis='y', labelcolor=color_cpu)
ax1.grid(True, linestyle='--', alpha=0.5)

# Secondo asse Y per la RAM nel Subplot 1
ax1_twin = ax1.twinx()  
color_ram = 'tab:blue'
ax1_twin.plot(df.index, df['RAM_GB'], color=color_ram, label='RAM Usage (GB)', linewidth=2)
ax1_twin.set_ylabel('RAM Usage (GB)', color=color_ram, fontsize=12)
ax1_twin.tick_params(axis='y', labelcolor=color_ram)

# Imposta un limite Y fisso per la RAM per mostrare visivamente quanto sia "piatta" e bassa
ax1_twin.set_ylim(0, 2) 

ax1.set_title("Utilizzo Risorse di Calcolo (CPU & RAM)", fontsize=14)
lines_1, labels_1 = ax1.get_legend_handles_labels()
lines_2, labels_2 = ax1_twin.get_legend_handles_labels()
